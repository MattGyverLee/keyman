// The modifier VKs Keyman manages. isModifierKey's nine VKs collapse onto these six.
const BYTE KeymanModifierVks[KEYMAN_MODIFIER_VK_COUNT] = {
  VK_LMENU, VK_RMENU, VK_LCONTROL, VK_RCONTROL, VK_LSHIFT, VK_RSHIFT
};

/**
  do_keybd_event adds a keyboard event into the keyboard event queue.

  Parameters: pInputs  array of INPUT structures which we will fill with our key events.
              n        pointer to current index into pInput, which we increment for each key
                       event we add

  This function mimics the keybd_event Windows API function, but instead of posting the event
  to the system keyboard event queue, it appends it to our internal event queue in pInputs.
  This allows us to send an atomic set of key events with SendInput.

  In this function, we map back the extended modifier keys. Now, the history of the PC keyboard
  means that this is a little weird. The original PC XT keyboard had Left and Right Shift keys,
  but only a single Ctrl and a single Alt key. This means, that the shift keys were each assigned
  their own scan code. However, Windows maps both keys to the same virtual key code (VK_SHIFT) for
  most purposes.

  When the Right Ctrl and Right Alt keys were introduced, they were differentiated from the original
  keys not by separate scan codes, but by an extended prefix byte (E0), together with the original
  scan code. Again, Windows does not differentiate with virtual keys (VK_CONTROL and VK_MENU).

  This means, to check for Left vs Right Shift, you need to test the scan code (2A and 36)
  respectively. However, to test for Left vs Right Ctrl/Alt, you need to test the Extended bit in
  the flags for the message.

  There are a few places where VK_LSHIFT, VK_RSHIFT, VK_LCONTROL, VK_RCONTROL, VK_LMENU, and
  VK_RMENU can be used, such as GetKeyState or MapVirtualKey. However, these virtual key codes
  should never be emitted and will never be received as a key event.

  To add an additional wrinkle to an already wrinkly story, Keyman (ab)uses the scan code property
  of key events to identify key events that it has synthesized, as opposed to those generated by
  the user or by another app (e.g. Remote Desktop scenarios). Instead of using the correct scan
  code, it will stuff the key event with a 0xFF scan code, and replace that in its GetMessage
  so the end application gets a look at the correct scan code. However, this will obviously not
  work with Right Shift, which is differentiated from Left Shift _only_ by scan code. Fortunately,
  we can afford to not care about this -- it means a little extra flag setting behind the scenes
  as the right shift key is released and re-pressed during key events, but nothing too dramatic.
*/
void do_keybd_event(LPINPUT pInputs, int *n, BYTE vk, BYTE scan, DWORD flags, ULONG_PTR extraInfo) {   // I4548
  INPUT input;
  input.type = INPUT_KEYBOARD;

  switch(vk) {
  case VK_RCONTROL:
    flags |= KEYEVENTF_EXTENDEDKEY;
    /*fallthrough*/
  case VK_LCONTROL:
    vk = VK_CONTROL;
    break;

  case VK_RMENU:
    flags |= KEYEVENTF_EXTENDEDKEY;
    /*fallthrough*/
  case VK_LMENU:
    vk = VK_MENU;
    break;

  case VK_RSHIFT:
    scan = SCANCODE_RSHIFT; // from kbd.h
    /*fallthrough*/
  case VK_LSHIFT:
    vk = VK_SHIFT;
    break;
  }

  input.ki.wVk = vk;
  input.ki.wScan = scan;
  input.ki.dwFlags = flags;
  input.ki.time = 0;
  input.ki.dwExtraInfo = extraInfo;
  SendDebugMessageFormat("n=%d, vk=%s, scan=%x, flags=%x", *n, Debug_VirtualKey(vk), scan, flags);

  pInputs[*n] = input;
  (*n)++;
}

/**
  keybd_sendprefix pushes a dummy keystroke into the keyboard event queue.

  Parameters: pInputs  array of INPUT structures which we will fill with our key events.
              n        pointer to current index into pInput, which we increment for each key
                       event we add

  The keybd_sendprefix call is needed, for example, if the user presses Alt+F which matches a rule
  in the current Keyman keyboard, because without the dummy prefix key, faking the release of the
  Alt key will activate the mainmenu of the current application.
*/
void keybd_sendprefix(LPINPUT pInputs, int *n)
{
  SendDebugEntry();
  //SendDebugMessageFormat("sending prefix down+up");
  do_keybd_event(pInputs, n, (BYTE) Globals::get_vk_prefix(), SCAN_FLAG_KEYMAN_KEY_EVENT, 0, 0);   // I4548   // I4844
  do_keybd_event(pInputs, n, (BYTE) Globals::get_vk_prefix(), SCAN_FLAG_KEYMAN_KEY_EVENT, KEYEVENTF_KEYUP, 0);   // I4548   // I4844
  SendDebugExit();
}

/**
  keybd_shift_release records the current keyboard state and then releases any modifier
  keys. If a modifier key must be released, it first sends a dummy prefix key to prevent
  isolated modifier key actions such as Alt opening up a menu.

  Parameters: pInputs  array of INPUT structures which we will fill with our key events.
              n        pointer to current index into pInput, which we increment for each key
                       event we add
              kbd      pointer to keyboard state (256 byte array), in which we will store
                       the initial modifier state for later restoration by keybd_shift_reset
              sendPrefix  FALSE suppresses the dummy prefix keystroke; see
                       PrepareModifierVerificationCorrection
*/
void keybd_shift_release(LPINPUT pInputs, int *n, LPBYTE const kbd, BOOL sendPrefix = TRUE) {
  BOOL hasSentPrefix = FALSE;

  SendDebugEntry();
  for (int i = 0; i < _countof(KeymanModifierVks); i++) {
    if (kbd[KeymanModifierVks[i]] & 0x80) {
      if (!hasSentPrefix && sendPrefix) {
        keybd_sendprefix(pInputs, n);
        hasSentPrefix = TRUE;
      }
      SendDebugMessageFormat("sending keyup vkey=%s", Debug_VirtualKey(KeymanModifierVks[i]));
      do_keybd_event(pInputs, n, KeymanModifierVks[i], SCAN_FLAG_KEYMAN_KEY_EVENT, KEYEVENTF_KEYUP, EXTRAINFO_FLAG_KEYMAN_MODIFIER_WRAP);
    }
  }
  SendDebugExit();
}

/**
  keybd_shift_reset returns the modifiers to their original pressed state and, if any modifier
  key presses are emitted, emits also a dummy 'prefix' keystroke in order to prevent default
  modifier actions such as Alt opening up a menu.

  Parameters: pInputs  array of INPUT structures which we will fill with our key events.
              n        pointer to current index into pInput, which we increment for each key
                       event we add
              kbd      pointer to keyboard state (256 byte array), previously set by
                       keybd_shift_release
              pPressIndex  optional out; KEYMAN_MODIFIER_VK_COUNT ints, one per slot of
                       KeymanModifierVks, set to the pInputs index of that modifier's KEYDOWN, or
                       -1 where none was emitted. Lets the caller handle a short SendInput (#8064)
*/
void keybd_shift_reset(LPINPUT pInputs, int *n, LPBYTE const kbd, int *pPressIndex = NULL) {
  BOOL needsPrefix = FALSE;

  SendDebugEntry();
  if (pPressIndex != NULL) {
    for (int i = 0; i < _countof(KeymanModifierVks); i++) {
      pPressIndex[i] = -1;
    }
  }

  for (int i = 0; i < _countof(KeymanModifierVks); i++) {
    if (kbd[KeymanModifierVks[i]] & 0x80) {
      SendDebugMessageFormat("sending keydown vkey=%s", Debug_VirtualKey(KeymanModifierVks[i]));
      if (pPressIndex != NULL) {
        pPressIndex[i] = *n; // the slot this KEYDOWN is about to occupy
      }
      do_keybd_event(pInputs, n, KeymanModifierVks[i], SCAN_FLAG_KEYMAN_KEY_EVENT, 0, EXTRAINFO_FLAG_KEYMAN_MODIFIER_WRAP);
      needsPrefix = TRUE;
    }
  }

  if (needsPrefix) {
    keybd_sendprefix(pInputs, n);
  }
  SendDebugExit();
}

/**
  keybd_shift evaluates the current keyboard modifier state and queues key events in order to
  initially set modifiers to "up" and, after the output key events are queued, resets the modifiers
  to their initial state.

  Parameters: pInputs  array of INPUT structures which we will fill with our key events.
              n        pointer to current index into pInput, which we increment for each key
                       event we add
              isReset  are we clearing or resetting the modifier state?
              kbd      pointer to keyboard state (256 byte array) that owner must maintain but
                       that we will fill

  There must be enough space in pInputs to contain 6 x up + 6 x down + 2 prefix-down + 2 prefix-up event = 16 events,
  to support both the clear and reset calls.
*/
void keybd_shift(LPINPUT pInputs, int *n, BOOL isReset, LPBYTE const kbd, int *pPressIndex) {
  if (isReset) {
    keybd_shift_reset(pInputs, n, kbd, pPressIndex);
  } else {
    keybd_shift_release(pInputs, n, kbd);
  }
}


/**
  CaptureLiveModifierState sets liveOut[vk] to 0x80 for each managed modifier the OS reports held.
  One reading per batch, so the reconcile and the release set agree. GetAsyncKeyState, because
  GetKeyState/GetKeyboardState read this thread's processed queue.
*/
void CaptureLiveModifierState(LPBYTE liveOut, PGETASYNCKEYSTATE pfnGetAsyncKeyState) {
  memset(liveOut, 0, 256);

  for (int i = 0; i < _countof(KeymanModifierVks); i++) {
    if (pfnGetAsyncKeyState(KeymanModifierVks[i]) < 0) {
      liveOut[KeymanModifierVks[i]] = 0x80;
    }
  }
}

/**
  ReconcileModifierCache clears any modifier the cache kbd reports held while live reports it up,
  and returns TRUE if they disagreed. A dropped modifier KEYUP otherwise leaves that byte set for
  the life of the process, and keybd_shift_reset presses the modifier for real (#8064). Clears but
  never sets: the user may release before SendInput runs.
*/
BOOL ReconcileModifierCache(LPBYTE const kbd, LPBYTE const live) {
  BOOL disagreed = FALSE;

  for (int i = 0; i < _countof(KeymanModifierVks); i++) {
    const BYTE vk = KeymanModifierVks[i];
    if ((kbd[vk] & 0x80) && !(live[vk] & 0x80)) {
      SendDebugMessageFormat("cache says held but OS says up, clearing vkey=%s", Debug_VirtualKey(vk));
      kbd[vk] = 0;
      disagreed = TRUE;
    }
  }

  return disagreed;
}

/**
  PrepareInjectedInputBatch assembles one injected batch into pInputs (MAX_KEYEVENT_INPUTS long)
  and returns the event count: release half, output keys, restore half. Optionally returns the
  restore half's presses as a bitmask over KeymanModifierVks, and the buffer index of each (-1 if
  none), so a short SendInput can be handled exactly.

  With the feed off, kbd never updates after its launch seed, so a release taken from live state
  could never be balanced by the restore, which reads kbd. Both halves then read kbd.
*/
int PrepareInjectedInputBatch(
  LPINPUT pInputs,
  LPBYTE const kbd,
  const SerialKeyEventSharedData *pSharedData,
  PGETASYNCKEYSTATE pfnGetAsyncKeyState,
  BOOL feedIsConfigured,
  DWORD *pRestorePressedMask,
  int *pRestoreEventIndex) {
  DWORD nInputs = min(pSharedData->nInputs, MAX_KEYEVENT_INPUTS);
  int n         = 0;

  BYTE live[256];
  CaptureLiveModifierState(live, pfnGetAsyncKeyState);

  // #8064 Clear before keybd_shift below presses it for real. Anything that skips this reconcile
  // must also skip the restore half, which would otherwise press a modifier nobody holds.
  ReconcileModifierCache(kbd, live);

  // The release set is live, the restore set is kbd, so a modifier the OS holds that the cache
  // does not claim is released and not pressed back. Accepted: releasing on the cache alone lets
  // a held Ctrl turn the keyboard's Backspaces into Ctrl+Backspace. Logged so a dead modifier can
  // be told from a stuck one.
  if (feedIsConfigured) {
    for (int i = 0; i < _countof(KeymanModifierVks); i++) {
      const BYTE vk = KeymanModifierVks[i];
      if ((live[vk] & 0x80) && !(kbd[vk] & 0x80)) {
        SendDebugMessageFormat(
          "#8064 dropped hold: released vkey=%s that the OS reports held and the cache does not claim, "
          "so the restore half will not press it back", Debug_VirtualKey(vk));
      }
    }
  }

  // After the reconcile kbd is a subset of live, so live covers both.
  keybd_shift(pInputs, &n, FALSE, feedIsConfigured ? live : kbd);

  for (DWORD i = 0; i < nInputs && n < MAX_KEYEVENT_INPUTS - MAX_KEYEVENT_INPUTS_MODIFIERS; i++, n++) {
    pInputs[n].type           = INPUT_KEYBOARD;
    pInputs[n].ki.wVk         = pSharedData->inputs[i].wVk;
    pInputs[n].ki.wScan       = pSharedData->inputs[i].wScan;
    pInputs[n].ki.dwFlags     = pSharedData->inputs[i].dwFlags;
    pInputs[n].ki.time        = pSharedData->inputs[i].time;
    pInputs[n].ki.dwExtraInfo = (ULONG_PTR)pSharedData->inputs[i].extraInfo;
  }

  // The restore set is kbd, not live: live state cannot tell "the user holds it" from "we pressed
  // it", so restoring from it manufactures unmatched presses.
  keybd_shift(pInputs, &n, TRUE, kbd, pRestoreEventIndex);

  if (pRestorePressedMask != NULL) {
    DWORD mask = 0;
    for (int i = 0; i < _countof(KeymanModifierVks); i++) {
      if (kbd[KeymanModifierVks[i]] & 0x80) {
        mask |= (1u << i);
      }
    }
    *pRestorePressedMask = mask;
  }

  return n;
}

/**
  PrepareModifierVerificationCorrection releases the modifiers in restorePressedMask that the OS
  still holds and the cache now says nobody holds: a batch's restore press can outlive a user
  release that raced it, and ReconcileModifierCache only catches that on the next batch.

  The prefix keystroke is sent only when an Alt is released, since this lands in whatever has
  focus by now. Known false positive: a user KEYDOWN still queued behind the verify message can be
  released. Accepted, as an unmatched KEYUP is re-pressable and an unmatched KEYDOWN on hardware
  with no Right Ctrl is not. Like ReconcileModifierCache, this only clears.
*/
int PrepareModifierVerificationCorrection(
  LPINPUT pInputs,
  LPBYTE const kbd,
  DWORD restorePressedMask,
  PGETASYNCKEYSTATE pfnGetAsyncKeyState) {
  int n = 0;

  BYTE live[256];
  CaptureLiveModifierState(live, pfnGetAsyncKeyState);

  BYTE correction[256];
  memset(correction, 0, 256);

  for (int i = 0; i < _countof(KeymanModifierVks); i++) {
    if (!(restorePressedMask & (1u << i))) {
      continue;
    }
    const BYTE vk = KeymanModifierVks[i];

    if (!(kbd[vk] & 0x80) && (live[vk] & 0x80)) {
      SendDebugMessageFormat("verification: OS holds vkey=%s that the cache says nobody holds, correcting", Debug_VirtualKey(vk));
      correction[vk] = 0x80;
    }
  }

  const BOOL hasAlt = (correction[VK_LMENU] & 0x80) || (correction[VK_RMENU] & 0x80);

  keybd_shift_release(pInputs, &n, correction, hasAlt);

  return n;
}

/**
  UpdateModifierCacheFromKeyEvent applies one modifier key event to the cache, collapsing the
  hook's VKs onto the chiral pair the cache is keyed by.
*/
void UpdateModifierCacheFromKeyEvent(LPBYTE kbd, BYTE bVk, BOOL fIsExtendedKey, BYTE bScan, BOOL fIsUp) {
  switch (bVk) {
  case VK_CONTROL:
    // Left and right control are distinguished by a 0xE0 prefix byte
    bVk = fIsExtendedKey ? VK_RCONTROL : VK_LCONTROL;
    break;
  case VK_MENU:
    // Left and right alt are distinguished by a 0xE0 prefix byte
    bVk = fIsExtendedKey ? VK_RMENU : VK_LMENU;
    break;
  case VK_SHIFT:
    // Left and right shift are distinguished by scan code alone
    bVk = bScan == SCANCODE_RSHIFT ? VK_RSHIFT : VK_LSHIFT;
    break;
  case VK_LCONTROL:
  case VK_RCONTROL:
  case VK_LSHIFT:
  case VK_RSHIFT:
  case VK_LMENU:
  case VK_RMENU:
    // These are technically not needed but perhaps some app will send them through SendInput
    // and we'll have to deal with them?
    break;
  default:
    return;
  }

  kbd[bVk] = fIsUp ? 0 : 0x80;
}

/**
  IsKeymanInjectedKeyEvent reports whether a key event the hook received was injected by Keyman
  rather than produced by the user's keyboard. Two arms, both needed. SCAN_FLAG_KEYMAN_KEY_EVENT
  catches the 0xFF scan overload, including the direct keybd_event callers, which cannot set
  dwExtraInfo. EXTRAINFO_FLAG_KEYMAN_MODIFIER_WRAP catches Right Shift, whose scan code
  do_keybd_event rewrites.

  Equality on the tag, never extraInfo != 0: mstsc stamps 0x4321DCBA on genuine remote user input.
  Not LLKHF_INJECTED: the OSK sets it too, and an OSK sticky modifier is meant to be real.
*/
BOOL IsKeymanInjectedKeyEvent(DWORD scanCode, ULONG_PTR extraInfo) {
  return scanCode == SCAN_FLAG_KEYMAN_KEY_EVENT || extraInfo == EXTRAINFO_FLAG_KEYMAN_MODIFIER_WRAP;
}

/**
  ShouldFeedModifierCache decides whether a modifier key event the hook received belongs in the
  serializer's modifier cache. Keyman's own injected modifiers must not feed it: a batch's restore
  press can outlive the user's release, leaving the cache holding a modifier nobody holds, which
  the reconcile cannot see because the OS agrees (#8064). Callers pass the raw scan code and
  dwExtraInfo, and call this before the "generated by Keyman" pass-through so modifiers are
  tracked with no Keyman keyboard active.
*/
BOOL ShouldFeedModifierCache(BOOL serializeInput, DWORD scanCode, ULONG_PTR extraInfo) {
  return serializeInput && !IsKeymanInjectedKeyEvent(scanCode, extraInfo);
}

/**
  PostKeyEventAndDecideEat hands a key event to the serial key event server and returns TRUE, so
  the hook eats it, only when the handoff succeeded. Eating a modifier KEYUP whose post failed
  leaves the OS and the cache both holding it (#8064); passing it through unserialized is the
  lesser failure. A NULL hwndServer must be checked: PostMessage to a NULL hwnd reports success
  and misroutes.
*/
BOOL PostKeyEventAndDecideEat(HWND hwndServer, DWORD vkCode, DWORD flags, PPOSTMESSAGEFN pfnPost) {
  if (hwndServer == NULL) {
    return FALSE;
  }

  return pfnPost(hwndServer, WM_KEYMAN_KEY_EVENT, vkCode, flags) ? TRUE : FALSE;
}
